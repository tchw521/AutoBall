package com.autoball.float

/**
 * **悬浮窗口统一字号**（sp）与行高。
 *
 * 触发 R-001 三次法则：此前字号散落各处、每个方法各写一个字面量，
 * 想整体缩小就得逐个改，还容易漏。现在改一处即可。
 *
 * 定档原则：**按信息层级递减，而不是一律同尺寸**——
 * - 必要信息（脚本名、动作行、按钮文案）：够看清即可，略缩；
 * - 描述性 / 次要信息（序号、删除键、菜单项、提示）：明显更小，
 *   它们只是辅助，不该和主内容抢视觉重量。
 */
object TextSz {

    /** 标题栏脚本名 */
    const val TITLE = 13.0f

    /** 动作列表主文案（必要信息，略缩） */
    const val ROW = 11.5f

    /** 动作行右侧删除键、序号（次要） */
    const val ROW_MINOR = 10.5f

    /** 更多菜单项（描述性，更小） */
    const val MENU = 11.0f

    /** 底部主条按钮文案 */
    const val BAR = 12.0f

    /** 提示 / 说明文字（最小一档） */
    const val NOTE = 9.5f

    /** 圆标图标（⚙ ⋮ ✕） */
    const val GLYPH = 12.5f

    /** 空态入口按钮 */
    const val BIG = 12.5f

    /** 状态点 */
    const val DOT = 8.0f

    /**
     * 列表行高（dp）。
     *
     * 34dp 时在"菜单展开、列表只剩 1/3 空间"的情况下勉强 3 行，
     * 收窄到 29dp 后能稳定显示 3 行以上。
     */
    const val ROW_H = 29f
}
