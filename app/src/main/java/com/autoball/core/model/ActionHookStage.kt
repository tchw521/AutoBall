package com.autoball.core.model

/**
 * **动作级**监听动作的 7 个触发阶段（自动精灵同款）。
 *
 * 与脚本级 9 时机（[com.autoball.ui.ListenerDialog.Stage]）是两回事：
 * 那个作用于整段脚本（脚本开始前 / 列表开头 / 结尾 …），
 * 这里只作用于**当前这一个动作**的生命周期。
 *
 * 早前动作级监听直接复用了脚本级的 9 个 key（SB/LT/BR…），
 * 于是动作上挂的钩子与脚本级钩子**共用同一批名字**，语义完全不同却互相覆盖。
 * 现在换成本枚举独立的 key，两者彻底分开。
 *
 * 每个阶段的说明文字都不同（见 [hint]）——这是这个对话框的主要信息量，
 * 用一句通用话术套七个阶段等于没说。
 */
enum class ActionHookStage(
    /** 存储 key，写入 `Action.listeners` */
    val key: String,
    val label: String,
    /** 列表副标题：一句话说清它挂在什么时候 */
    val desc: String,
    /** 「?」气泡里的完整说明 */
    val hint: String
) {
    BEFORE_COND(
        "cb", "检查运行条件前", "条件判定之前",
        "检查运行条件前，先运行这个监听动作。\n" +
        "如果动作没有设置运行条件，则不会运行这个监听动作。"
    ),
    COND_OK(
        "co", "运行条件满足后", "条件成立之后",
        "检查运行条件满足后，再运行这个监听动作。\n" +
        "如果动作没有设置运行条件，则不会运行这个监听动作。"
    ),
    COND_FAIL(
        "cf", "运行条件失败后", "条件不成立之后",
        "检查运行条件失败后，再运行这个监听动作。\n" +
        "如果动作没有设置运行条件，则不会运行这个监听动作。\n" +
        "注意：能力不足导致「无法判定」也按失败处理，同样会触发。"
    ),
    BEFORE_RUN(
        "rb", "动作开始运行前", "真正执行之前",
        "开始运行前（检查运行条件且满足后），先运行这个监听动作。\n" +
        "条件不满足、动作被跳过时不会运行。"
    ),
    AFTER_OK(
        "ra", "动作运行成功后", "每次成功都触发",
        "满足运行条件且动作运行成功后，再运行这个监听动作。\n" +
        "若设置了重复次数，每次执行成功都会触发监听。"
    ),
    AFTER_FAIL(
        "rf", "动作运行失败后", "失败时兜底",
        "满足运行条件且动作运行失败后，再运行这个监听动作。\n" +
        "若设置则会忽略默认的「运行失败暂停」和「全局失败监听动作」。"
    ),
    AFTER_END(
        "re", "动作运行结束后", "无论成败都收尾",
        "动作结束后再运行这个监听动作。\n" +
        "重复次数会在**全部完成**后只触发一次（与「运行成功后」不同）。\n" +
        "正常结束、失败结束、条件跳过都会进入；跳转跳出则不进入。"
    ),
    ;

    companion object {
        fun byKey(k: String): ActionHookStage? = values().firstOrNull { it.key == k }

        /** 该动作上实际挂了几个钩子 */
        fun countOf(a: Action): Int = values().count { a.listeners[it.key] != null }

        /**
         * 编辑动作页「监听动作」行的摘要。
         *
         * 必须显示**具体挂了哪个阶段**，而不是笼统的「已设置 3 项」——
         * 七个阶段语义差别很大（"条件失败后"和"运行成功后"是两回事），
         * 只给数字的话用户得点进去才知道自己配了什么。
         *
         * - 0 项：`未设置`
         * - 1 项：`检查运行条件前`（直接给阶段名，尽可能完整）
         * - 多项：`检查运行条件前 等 3 项`（首个阶段名 + 总数，
         *   全列出来会被截断成省略号，反而看不清）
         */
        fun summaryOf(a: Action): String {
            val hit = values().filter { a.listeners[it.key] != null }
            if (hit.isEmpty()) return "未设置"
            if (hit.size == 1) return hit[0].label
            return "${hit[0].label} 等 ${hit.size} 项"
        }
    }
}
